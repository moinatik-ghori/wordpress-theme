/**
 * Edit component for Tech Stack Badge block.
 *
 * @param {Object} props Block props.
 * @param {Object} props.attributes Block attributes.
 * @param {Function} props.setAttributes Set attributes function.
 * @return {JSX.Element} Block editor component.
 */
export default function Edit( { attributes, setAttributes } ) {
	const { technology, showIcon, size } = attributes;

	const blockProps = useBlockProps( {
		className: `badge badge--tech badge--${ technology.toLowerCase().replace( /\s+/g, '-' ) } badge--${ size }`,
	} );

	return (
		<>
			<InspectorControls>
				<PanelBody title="Badge Settings">
					<SelectControl
						label="Technology"
						value={ technology }
						options={ technologyOptions }
						onChange={ ( value ) => setAttributes( { technology: value } ) }
					/>
					<SelectControl
						label="Size"
						value={ size }
						options={ sizeOptions }
						onChange={ ( value ) => setAttributes( { size: value } ) }
					/>
					<ToggleControl
						label="Show Icon"
						checked={ showIcon }
						onChange={ ( value ) => setAttributes( { showIcon: value } ) }
					/>
				</PanelBody>
			</InspectorControls>

			<span { ...blockProps }>
				{ showIcon && (
					<span
						className="badge__icon"
						dangerouslySetInnerHTML={ { __html: getTechnologyIcon( technology ) } }
					/>
				) }
				<span className="badge__text">{ technology }</span>
			</span>
		</>
	);
}

